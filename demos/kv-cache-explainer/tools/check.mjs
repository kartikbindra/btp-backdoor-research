import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const html=await fs.readFile(path.join(root,'dist/index.html'),'utf8');
const offline=await fs.readFile(path.join(root,'dist/kv-cache-explainer-offline.html'),'utf8');
assert.equal(html,offline,'Offline copy must match the hosted document');
assert.ok(!/<script[^>]+src=/i.test(html),'Scripts must be embedded for offline use');
assert.ok(!/<link[^>]+rel=["']stylesheet/i.test(html),'Styles must be embedded for offline use');
const embedded=html.match(/<script id="evidence-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(embedded,'Missing embedded evidence');
const data=JSON.parse(embedded[1]);
assert.equal(data.cases[0].result.P,346);assert.equal(data.cases[0].result.n_evicted,35);assert.equal(data.cases[0].result.trig_hit,1);
assert.equal(data.cases[1].result.P,366);assert.equal(data.cases[1].result.n_evicted,37);assert.equal(data.cases[1].result.trig_hit,0);
assert.equal(data.summary.triggered,1022);assert.equal(data.summary.longPrompts,1122);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].filter(m=>!m[0].includes('application/json'));
assert.equal(scripts.length,1);
new vm.Script(scripts[0][1],{filename:'inline-replay.js'});
assert.equal((html.match(/data-step="[0-5]"/g)??[]).length,6);
assert.ok(html.includes('Exact counts. Schematic position layout.'));
assert.ok(html.includes('does not demonstrate eviction of an already-built ordinary cache'));
console.log(JSON.stringify({passed:true,offlineSelfContained:true,evidenceCases:2,steps:6,inlineScriptSyntax:'valid'}));
